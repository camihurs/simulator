"""Rigid-sphere free-field echo using the OpenSTB Fourier convention.

This standalone intentionally keeps only the source and target-scattering physics.  It
uses the same analytic-signal FFT/IFFT convention as OpenSTB, but does not include
propagation loss, absorption, transducer beampatterns, Doppler, or platform geometry.

The historical ``RigidSphereEcho.py`` is preserved unchanged as the original Rudgers
validation script.  This file is the clean, general-purpose standalone.
"""

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from scipy.special import eval_legendre, spherical_jn, spherical_yn

# =============================================================================
# USER CONFIGURATION
# =============================================================================

# Available cases: "rudgers_fig6", "tone_burst", "lfm_chirp".
SOURCE_CASE = "lfm_chirp"

# Normal use produces three figures: source, form function, and echo.  The options
# below add scientific diagnostics for the Rudgers reference case.
SHOW_VALIDATION_PLOTS = True
COMPARE_DIRECT_RUDGERS = True
COMPARE_OPENSTB_DUMP = True

# Target and medium.
SOUND_SPEED_M_S = 1480.0
SPHERE_RADIUS_M = 0.25
SCATTERING_ANGLE_RAD = np.pi
N_TERMS = 80
KA_EPS = 1e-8

# Numerical record.  The sample rate is selected per source case below.
N_FFT = 16384
RECORD_DURATION_FACTOR = 3.0
FORM_FUNCTION_PLOT_KA_MAX = 14.0

# General tone-burst parameters.  The Rudgers preset overrides these with k0a=15
# and two cycles.
TONE_FREQUENCY_HZ = 14_000.0
TONE_CYCLES = 4.0

# General analytic LFM parameters, chosen to match the OpenSTB experiment defaults.
CHIRP_START_HZ = 500.0
CHIRP_STOP_HZ = 10_000.0
CHIRP_DURATION_S = 0.020
CHIRP_SAMPLE_RATE_HZ = 30_000.0
CHIRP_USE_HANN_WINDOW = True

# The dump is optional.  It must be generated by the controlled rigid-sphere
# OpenSTB configuration described in the experiment README/handoff.
OPENSTB_DUMP = (
    Path(__file__).resolve().parents[3]
    / "simple_points_study"
    / "rigid_sphere_ff_debug.npz"
)


def compute_form_function(
    ka_values: np.ndarray,
    theta: float = np.pi,
    n_terms: int = N_TERMS,
    ka_eps: float = KA_EPS,
) -> np.ndarray:
    """Return Rudgers' far-field rigid-sphere form function.

    The expression is Eq. (11) of Rudgers for an arbitrary scattering angle.  It
    has the same complex convention as ``RigidSphereFormFunction`` in OpenSTB.
    """

    ka = np.asarray(ka_values, dtype=float)
    if np.any(ka < 0):
        raise ValueError("ka_values must be non-negative")

    ka_safe = np.maximum(ka, ka_eps)
    result = np.zeros_like(ka_safe, dtype=np.complex128)
    cos_theta = np.cos(theta)

    for n in range(n_terms):
        jn_prime = spherical_jn(n, ka_safe, derivative=True)
        yn_prime = spherical_yn(n, ka_safe, derivative=True)
        eta_n = np.arctan2(jn_prime, -yn_prime)
        coefficient = (2 * n + 1) * np.sin(eta_n) * np.exp(1j * eta_n)
        result += coefficient * eval_legendre(n, cos_theta)

    result *= -2.0 / ka_safe
    result = np.nan_to_num(result, nan=0.0, posinf=0.0, neginf=0.0)
    result = np.where(ka == 0.0, 0.0 + 0.0j, result)
    return result


def build_source() -> dict[str, object]:
    """Build one analytic source using the same sign convention as OpenSTB."""

    if SOURCE_CASE == "rudgers_fig6":
        k0a = 15.0
        f0 = k0a * SOUND_SPEED_M_S / (2 * np.pi * SPHERE_RADIUS_M)
        n_cycles = 2.0
        duration = n_cycles / f0
        sample_rate = 10.0 * f0
        baseband_frequency = 0.0
        label = "Rudgers Fig. 6: two-cycle tone burst, k0a=15"

        def evaluate(t: np.ndarray) -> np.ndarray:
            valid = (t >= 0.0) & (t < duration)
            signal = np.zeros_like(t, dtype=np.complex128)
            # Analytic equivalent of sin(2*pi*f0*t), matching OpenSTB SinusoidBurst.
            phase = 2 * np.pi * f0 * t[valid] - np.pi / 2
            signal[valid] = np.exp(1j * phase)
            return signal

    elif SOURCE_CASE == "tone_burst":
        f0 = TONE_FREQUENCY_HZ
        n_cycles = TONE_CYCLES
        duration = n_cycles / f0
        sample_rate = 10.0 * f0
        baseband_frequency = 0.0
        k0a = 2 * np.pi * f0 * SPHERE_RADIUS_M / SOUND_SPEED_M_S
        label = f"Analytic {n_cycles:g}-cycle tone burst, k0a={k0a:.3f}"

        def evaluate(t: np.ndarray) -> np.ndarray:
            valid = (t >= 0.0) & (t < duration)
            signal = np.zeros_like(t, dtype=np.complex128)
            phase = 2 * np.pi * f0 * t[valid] - np.pi / 2
            signal[valid] = np.exp(1j * phase)
            return signal

    elif SOURCE_CASE == "lfm_chirp":
        f0 = None
        n_cycles = None
        k0a = None
        duration = CHIRP_DURATION_S
        sample_rate = CHIRP_SAMPLE_RATE_HZ
        baseband_frequency = 0.5 * (CHIRP_START_HZ + CHIRP_STOP_HZ)
        label = (
            f"Analytic LFM chirp, {CHIRP_START_HZ / 1e3:g}-{CHIRP_STOP_HZ / 1e3:g} kHz"
        )

        def evaluate(t: np.ndarray) -> np.ndarray:
            valid = (t >= 0.0) & (t <= duration)
            tv = t[valid]
            signal = np.zeros_like(t, dtype=np.complex128)
            fd = CHIRP_START_HZ - baseband_frequency
            chirp_rate = (CHIRP_STOP_HZ - CHIRP_START_HZ) / duration
            signal[valid] = np.exp(1j * np.pi * tv * (2 * fd + chirp_rate * tv))
            if CHIRP_USE_HANN_WINDOW:
                # Continuous Hann window, zero at both pulse endpoints.
                signal[valid] *= 0.5 * (1.0 - np.cos(2 * np.pi * tv / duration))
            return signal

    else:
        raise ValueError(f"Unknown SOURCE_CASE: {SOURCE_CASE!r}")

    record_duration = RECORD_DURATION_FACTOR * duration
    n_samples = max(2, int(np.ceil(record_duration * sample_rate)))
    t = np.arange(n_samples) / sample_rate
    signal = evaluate(t)

    return {
        "label": label,
        "time_s": t,
        "signal": signal,
        "sample_rate_hz": sample_rate,
        "baseband_frequency_hz": baseband_frequency,
        "duration_s": duration,
        "f0_hz": f0,
        "n_cycles": n_cycles,
        "k0a": k0a,
    }


def synthesize_echo(source: dict[str, object]) -> dict[str, np.ndarray]:
    """Apply the rigid-sphere response with the OpenSTB FFT/IFFT convention."""

    signal = np.asarray(source["signal"], dtype=np.complex128)
    sample_rate = float(source["sample_rate_hz"])
    baseband_frequency = float(source["baseband_frequency_hz"])

    frequency_offset = np.fft.fftshift(np.fft.fftfreq(N_FFT, d=1.0 / sample_rate))
    physical_frequency = frequency_offset + baseband_frequency
    source_spectrum = np.fft.fftshift(np.fft.fft(signal, n=N_FFT))

    # OpenSTB's rigid-sphere plugin evaluates the positive-frequency modal formula
    # using the magnitude of the physical frequency grid.
    ka = 2 * np.pi * np.abs(physical_frequency) * SPHERE_RADIUS_M / SOUND_SPEED_M_S
    form_function = compute_form_function(ka, theta=SCATTERING_ANGLE_RAD)
    echo_spectrum = source_spectrum * form_function
    echo_baseband = np.fft.ifft(np.fft.ifftshift(echo_spectrum))

    time_s = np.arange(N_FFT) / sample_rate
    echo_passband = np.real(
        echo_baseband * np.exp(1j * 2 * np.pi * baseband_frequency * time_s)
    )

    # Centered coordinates are useful because this standalone applies no propagation
    # delay; the target impulse response wraps around the FFT record origin.
    centered_time_s = (np.arange(N_FFT) - N_FFT // 2) / sample_rate

    return {
        "frequency_hz": physical_frequency,
        "frequency_offset_hz": frequency_offset,
        "source_spectrum": source_spectrum,
        "ka": ka,
        "form_function": form_function,
        "echo_spectrum": echo_spectrum,
        "echo_baseband": echo_baseband,
        "echo_passband": echo_passband,
        "centered_time_s": centered_time_s,
        "echo_baseband_centered": np.fft.fftshift(echo_baseband),
        "echo_passband_centered": np.fft.fftshift(echo_passband),
    }


def rudgers_spectrum(ka: np.ndarray, k0a: float, cycles: float) -> np.ndarray:
    """Return Rudgers' positive-ka spectrum from the defining Fourier integral."""

    pulse_length_tau = 2 * cycles * np.pi / k0a

    def exponential_integral(q: np.ndarray) -> np.ndarray:
        # Integral from 0 to m of exp(-i*q*tau) d(tau), stable at q=0.
        return (
            pulse_length_tau
            * np.exp(-0.5j * q * pulse_length_tau)
            * np.sinc(q * pulse_length_tau / (2 * np.pi))
        )

    return -1j * (exponential_integral(ka - k0a) - exponential_integral(ka + k0a))


def direct_rudgers_echo() -> tuple[np.ndarray, np.ndarray]:
    """Evaluate Rudgers Eq. (8) directly for an independent validation curve."""

    ka = np.linspace(0.0, 32.0 * np.pi, 12000)
    spectrum = rudgers_spectrum(ka, k0a=15.0, cycles=2.0)
    form_function = compute_form_function(ka, theta=np.pi)
    integrand = spectrum * form_function

    tau = np.linspace(-4.0, 10.0, 1401)
    echo = np.empty_like(tau)
    for index, tau_value in enumerate(tau):
        echo[index] = np.real(
            np.trapezoid(integrand * np.exp(1j * ka * tau_value), ka) / (2 * np.pi)
        )

    echo /= np.max(np.abs(echo)) + np.finfo(float).eps
    return tau, echo


def load_openstb_dump() -> dict[str, np.ndarray] | None:
    """Load a compatible controlled-validation dump, or report why it is skipped."""

    if not OPENSTB_DUMP.exists():
        print(f"OpenSTB comparison skipped; dump not found: {OPENSTB_DUMP}")
        return None

    with np.load(OPENSTB_DUMP) as data:
        required = {"f_hz", "ka", "ff_complex", "S_in_complex", "theta_sample_rad"}
        missing = required.difference(data.files)
        if missing:
            print(f"OpenSTB comparison skipped; dump is missing: {sorted(missing)}")
            return None
        dump = {name: np.asarray(data[name]) for name in required}

    lengths = {
        np.ravel(dump["f_hz"]).size,
        np.ravel(dump["ka"]).size,
        np.ravel(dump["ff_complex"]).size,
        np.ravel(dump["S_in_complex"]).size,
    }
    if len(lengths) != 1:
        print(
            "OpenSTB comparison skipped; incompatible dump array lengths: "
            f"f={dump['f_hz'].size}, ka={dump['ka'].size}, "
            f"ff={dump['ff_complex'].size}, S={dump['S_in_complex'].size}"
        )
        return None

    return dump


def normalized(values: np.ndarray) -> np.ndarray:
    """Normalize an array by its maximum absolute value without dividing by zero."""

    values = np.asarray(values)
    return values / (np.max(np.abs(values)) + np.finfo(float).eps)


def plot_standard_results(
    source: dict[str, object], result: dict[str, np.ndarray]
) -> None:
    """Plot the three concise figures produced in normal standalone use."""

    source_time = np.asarray(source["time_s"])
    source_signal = np.asarray(source["signal"])
    frequency = result["frequency_hz"]
    source_spectrum = result["source_spectrum"]
    ka = result["ka"]
    ff = result["form_function"]

    significant = np.abs(source_spectrum) > np.max(np.abs(source_spectrum)) * 1e-4
    positive_physical = frequency >= 0.0

    is_lfm = SOURCE_CASE == "lfm_chirp"
    row_count = 3 if is_lfm else 2
    fig, axes = plt.subplots(row_count, 1, figsize=(11, 9 if is_lfm else 7))
    ax_baseband = axes[0]
    ax_spectrum = axes[-1]

    baseband_label = "complex baseband real part" if is_lfm else "physical real part"
    ax_baseband.plot(source_time * 1e3, np.real(source_signal), label=baseband_label)
    ax_baseband.plot(
        source_time * 1e3,
        np.abs(source_signal),
        "k--",
        alpha=0.65,
        label="analytic envelope",
    )
    ax_baseband.set(
        xlabel="Time [ms]", ylabel="Amplitude", title=str(source["label"])
    )
    ax_baseband.grid(True, alpha=0.3)
    ax_baseband.legend()

    if is_lfm:
        ax_passband = axes[1]
        baseband_frequency = float(source["baseband_frequency_hz"])
        physical_signal = np.real(
            source_signal * np.exp(1j * 2 * np.pi * baseband_frequency * source_time)
        )
        ax_passband.plot(
            source_time * 1e3, physical_signal, label="reconstructed physical chirp"
        )
        ax_passband.plot(
            source_time * 1e3,
            np.abs(source_signal),
            "k--",
            alpha=0.65,
            label="analytic envelope",
        )
        ax_passband.set(
            xlabel="Time [ms]",
            ylabel="Amplitude",
            title=(
                "Physical passband view: monotonically increasing frequency "
                f"({CHIRP_START_HZ / 1e3:g}-{CHIRP_STOP_HZ / 1e3:g} kHz)"
            ),
        )
        ax_passband.grid(True, alpha=0.3)
        ax_passband.legend()

        active_xlim_ms = (-0.02 * float(source["duration_s"]) * 1e3,
                          1.02 * float(source["duration_s"]) * 1e3)
        ax_baseband.set_xlim(*active_xlim_ms)
        ax_passband.set_xlim(*active_xlim_ms)

    plot_mask = significant & positive_physical
    ax_spectrum.plot(
        frequency[plot_mask] / 1e3, normalized(np.abs(source_spectrum[plot_mask]))
    )
    ax_spectrum.set(
        xlabel="Physical frequency [kHz]",
        ylabel="Normalized magnitude",
        title="Incident analytic-signal spectrum",
    )
    ax_spectrum.grid(True, alpha=0.3)
    fig.tight_layout()

    order = np.argsort(ka)
    fig, (ax_mag, ax_phase) = plt.subplots(2, 1, figsize=(11, 7))
    ax_mag.plot(ka[order], np.abs(ff[order]))
    ax_mag.set(
        xlabel="ka",
        ylabel="|f(ka)|",
        title="Rigid-sphere form function",
        xlim=(0, FORM_FUNCTION_PLOT_KA_MAX),
    )
    ax_mag.grid(True, alpha=0.3)
    ax_phase.plot(ka[order], np.mod(np.angle(ff[order]), 2 * np.pi))
    ax_phase.set(
        xlabel="ka",
        ylabel="arg[f(ka)] [rad]",
        xlim=(0, FORM_FUNCTION_PLOT_KA_MAX),
        ylim=(0, 2 * np.pi),
    )
    ax_phase.grid(True, alpha=0.3)
    fig.tight_layout()

    echo = normalized(result["echo_passband_centered"])
    echo_spectrum = result["echo_spectrum"]
    fig, (ax_echo, ax_echo_spectrum) = plt.subplots(2, 1, figsize=(11, 7))
    ax_echo.plot(result["centered_time_s"] * 1e3, echo)
    ax_echo.set(
        xlabel="Time relative to FFT origin [ms]",
        ylabel="Normalized pressure",
        title="Rigid-sphere echo (target response only)",
    )
    ax_echo.grid(True, alpha=0.3)
    visible_echo = np.abs(echo) > 1e-3
    if np.any(visible_echo):
        visible_time = result["centered_time_s"][visible_echo] * 1e3
        padding = max(0.05, 0.1 * (visible_time.max() - visible_time.min()))
        ax_echo.set_xlim(visible_time.min() - padding, visible_time.max() + padding)
    ax_echo_spectrum.plot(
        frequency[plot_mask] / 1e3,
        normalized(np.abs(echo_spectrum[plot_mask])),
    )
    ax_echo_spectrum.set(
        xlabel="Physical frequency [kHz]",
        ylabel="Normalized magnitude",
        title="Scattered spectrum",
    )
    ax_echo_spectrum.grid(True, alpha=0.3)
    fig.tight_layout()


def plot_rudgers_validation(
    source: dict[str, object], result: dict[str, np.ndarray]
) -> None:
    """Add Rudgers-specific diagnostics without changing the canonical synthesis."""

    if SOURCE_CASE != "rudgers_fig6":
        print("Rudgers validation plots skipped; select SOURCE_CASE='rudgers_fig6'.")
        return

    positive = result["frequency_hz"] >= 0.0
    ka = result["ka"][positive]
    numerical_spectrum = result["source_spectrum"][positive]
    paper_spectrum = rudgers_spectrum(ka, k0a=15.0, cycles=2.0)
    order = np.argsort(ka)

    fig, ax = plt.subplots(figsize=(11, 4.5))
    ax.plot(
        ka[order], normalized(np.abs(numerical_spectrum[order])), label="analytic FFT"
    )
    ax.plot(
        ka[order],
        normalized(np.abs(paper_spectrum[order])),
        "--",
        label="Rudgers defining integral",
    )
    ax.set(xlabel="ka", ylabel="Normalized |g(ka)|", xlim=(0, 30))
    ax.grid(True, alpha=0.3)
    ax.legend()
    fig.tight_layout()

    if COMPARE_DIRECT_RUDGERS:
        tau_direct, echo_direct = direct_rudgers_echo()
        tau_fft = result["centered_time_s"] * SOUND_SPEED_M_S / SPHERE_RADIUS_M
        echo_fft = normalized(result["echo_passband_centered"])

        fig, ax = plt.subplots(figsize=(11, 4.5))
        ax.plot(tau_fft, echo_fft, label="analytic FFT/IFFT")
        ax.plot(tau_direct, echo_direct, "--", label="direct Rudgers Eq. (8)")
        ax.set(
            xlabel=r"Normalized time $\tau=tc/a$",
            ylabel="Normalized pressure",
            title="Rudgers reference echo",
            xlim=(-4, 10),
            ylim=(-1.1, 1.1),
        )
        ax.grid(True, alpha=0.3)
        ax.legend()
        fig.tight_layout()


def compare_openstb_dump() -> None:
    """Verify that the standalone modal function equals the controlled plugin dump."""

    dump = load_openstb_dump()
    if dump is None:
        return

    ka = np.ravel(dump["ka"]).astype(float)
    ff_openstb = np.ravel(dump["ff_complex"]).astype(np.complex128)
    theta = float(dump["theta_sample_rad"])
    ff_standalone = compute_form_function(ka, theta=theta)

    # The standalone assigns the physical limiting value f(0)=0 explicitly, whereas
    # the plugin evaluates the removable singularity at ka_eps.  Exclude only that DC
    # convention from the numerical comparison.
    significant = (ka > KA_EPS) & (
        np.abs(ff_openstb) > np.max(np.abs(ff_openstb)) * 1e-10
    )
    magnitude_error = np.linalg.norm(
        np.abs(ff_standalone[significant]) - np.abs(ff_openstb[significant])
    ) / (np.linalg.norm(np.abs(ff_openstb[significant])) + np.finfo(float).eps)
    phase_difference = np.angle(
        np.exp(
            1j
            * (np.angle(ff_standalone[significant]) - np.angle(ff_openstb[significant]))
        )
    )
    phase_rms = np.sqrt(np.mean(phase_difference**2))

    print("\nControlled OpenSTB form-function comparison")
    print(f"  dump: {OPENSTB_DUMP}")
    print(f"  samples: {ka.size}")
    print(f"  scattering angle: {theta:.10f} rad")
    print(f"  relative L2 magnitude error: {magnitude_error:.3e}")
    print(f"  RMS wrapped phase error: {phase_rms:.3e} rad")

    order = np.argsort(ka)
    fig, (ax_mag, ax_phase) = plt.subplots(2, 1, figsize=(11, 7))
    ax_mag.plot(ka[order], np.abs(ff_openstb[order]), label="OpenSTB dump")
    ax_mag.plot(ka[order], np.abs(ff_standalone[order]), "--", label="standalone")
    ax_mag.set(xlabel="ka", ylabel="|f(ka)|")
    ax_mag.grid(True, alpha=0.3)
    ax_mag.legend()
    ax_phase.plot(
        ka[order], np.mod(np.angle(ff_openstb[order]), 2 * np.pi), label="OpenSTB dump"
    )
    ax_phase.plot(
        ka[order],
        np.mod(np.angle(ff_standalone[order]), 2 * np.pi),
        "--",
        label="standalone",
    )
    ax_phase.set(xlabel="ka", ylabel="arg[f(ka)] [rad]", ylim=(0, 2 * np.pi))
    ax_phase.grid(True, alpha=0.3)
    ax_phase.legend()
    fig.tight_layout()


def main() -> None:
    source = build_source()
    result = synthesize_echo(source)

    print("Rigid-sphere analytic standalone")
    print(f"  source case: {SOURCE_CASE}")
    print(f"  source: {source['label']}")
    print(f"  sample rate: {float(source['sample_rate_hz']):.3f} Hz")
    print(f"  FFT points: {N_FFT}")
    print(f"  baseband frequency: {float(source['baseband_frequency_hz']):.3f} Hz")
    print(
        f"  finite form-function samples: {np.isfinite(result['form_function']).mean():.3f}"
    )
    print(f"  finite echo samples: {np.isfinite(result['echo_baseband']).mean():.3f}")

    plot_standard_results(source, result)
    if SHOW_VALIDATION_PLOTS:
        plot_rudgers_validation(source, result)
    if COMPARE_OPENSTB_DUMP:
        compare_openstb_dump()
    plt.show()


if __name__ == "__main__":
    main()
